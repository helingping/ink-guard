/**
 * Writes web-preview/game.js, a classic script the phone preview host can run.
 * Source of truth stays sim.mjs and main.mjs. Regenerate after editing those.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const configs = {};
for (const name of ['units', 'economy', 'adou', 'waves', 'board']) {
  configs[name] = JSON.parse(fs.readFileSync(path.join(dir, 'configs', `${name}.json`), 'utf8'));
}
const sim = fs.readFileSync(path.join(dir, 'sim.mjs'), 'utf8').replace(/^export /gm, '');
const main = fs
  .readFileSync(path.join(dir, 'main.mjs'), 'utf8')
  .replace(/^import[\s\S]*?from '\.\/sim\.mjs';\r?\n/, '');
const banner = `/* Generated by build-classic.mjs. Edit sim.mjs and main.mjs, then rerun it. */\n'use strict';\nglobalThis.INK_GUARD_CONFIGS = ${JSON.stringify(configs)};\n`;
fs.writeFileSync(path.join(dir, 'game.js'), `${banner}${sim}\n${main}`);
console.log('wrote web-preview/game.js');
